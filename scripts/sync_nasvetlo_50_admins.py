def post_egov_json(endpoint: str, payload: dict[str, Any], timeout: int = 25) -> dict[str, Any]:
    url = f"https://data.egov.bg/api/{endpoint}"
    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(url, data=data, headers=HEADERS_JSON, method="POST")
    with urllib.request.urlopen(req, context=SSL_CTX, timeout=timeout) as resp:
        raw = resp.read().decode("utf-8", errors="ignore").lstrip("\ufeff")
    return json.loads(raw)


def fetch_html_cached(url: str, cache_name: str, timeout: int = 25) -> str:
    cache_file = CACHE_DIR / cache_name
    if cache_file.exists() and cache_file.stat().st_size > 200 and (time.time() - cache_file.stat().st_mtime) < 86400:
        return cache_file.read_text(encoding="utf-8", errors="ignore")
    for attempt in range(2):
        try:
            time.sleep(0.22 + attempt * 0.8)
            req = urllib.request.Request(url, headers=HEADERS_GET, method="GET")
            with urllib.request.urlopen(req, context=SSL_CTX, timeout=timeout) as resp:
                txt = resp.read().decode("utf-8", errors="ignore")
            if len(txt) > 200:
                cache_file.write_text(txt, encoding="utf-8")
                return txt
        except Exception:
            pass
    return ""


def _norm_bg_org(text: str) -> str:
    t = html.unescape(text or "").lower()
    t = re.sub(r'[„“"\'«»`–—-]+', " ", t)
    t = re.sub(r"\s+", " ", t).strip()
    return t


def _match_org_score(org_name: str, kw: str) -> int | None:
    """Return relevance score (lower is better) if org_name genuinely matches kw, else None."""
    n_org = _norm_bg_org(org_name)
    n_kw = _norm_bg_org(kw)
    if not n_org or not n_kw:
        return None
    # Reject sub-units / unrelated entities unless keyword explicitly asks for them
    reject_markers = (
        "детска градина", "училище", "гимназия", "читалище", "кметство",
        "район ", "областна дирекция", "териториална дирекция", "регионална инспекция",
        "регионално управление", "басейнова дирекция", "център за спешна", "болница",
        "мбал", "умбал", "дирекция социално подпомагане", "бюро по труда",
    )
    for rm in reject_markers:
        if rm in n_org and rm not in n_kw:
            return None
    if n_org == n_kw:
        return 0
    if n_org.startswith(n_kw):
        return 1 + max(0, len(n_org) - len(n_kw))
    tokens = [w for w in n_kw.split() if len(w) >= 3]
    if not tokens:
        tokens = n_kw.split()
    if all(tok in n_org for tok in tokens):
        # For municipalities, require the name to start with "община " or "столична община"
        if n_kw.startswith("община ") and not n_org.startswith(n_kw):
            return None
        if n_kw.startswith("столична община") and not n_org.startswith("столична община"):
            return None
        return 10 + max(0, len(n_org) - len(n_kw))
    return None


def search_egov_orgs_live(keywords: list[str]) -> list[dict[str, str]]:
    """Search ALL 547 Bulgarian organisations on data.egov.bg via /organisation?q=...&type=2."""
    found: list[dict[str, str]] = []
    seen: set[str] = set()
    for kw in keywords:
        slug = re.sub(r"[^a-zA-Z0-9а-яА-Я]+", "_", kw)[:45]
        candidates: list[tuple[int, str, str]] = []
        for org_type in (2, 1):
            url = f"https://data.egov.bg/organisation?q={urllib.parse.quote(kw)}&type={org_type}"
            page = fetch_html_cached(url, f"q_{org_type}_{slug}.html")
            for m in re.finditer(
                r'href="https://data\.egov\.bg/organisation/profile/([a-f0-9-]+)(?:\?[^"]*)?"[^>]*>\s*<h3[^>]*class="org-name"[^>]*>(.*?)</h3>',
                page,
                re.I | re.S,
            ):
                uri = m.group(1)
                title = html.unescape(re.sub(r"<[^>]+>", "", m.group(2)))
                title = re.sub(r"\s+", " ", title).strip()
                score = _match_org_score(title, kw)
                if score is not None:
                    candidates.append((score, uri, title))
            if candidates:
                break
        candidates.sort(key=lambda x: x[0])
        # Pick the primary matching org for this keyword (or top 2 if exact ties/very close)
        for score, uri, title in candidates[:1]:
            if uri not in seen:
                seen.add(uri)
                found.append({"uri": uri, "name": title})
    return found


def fetch_egov_org_inventory(org_uri: str) -> dict[str, Any]:
    """Fetch exact dataset count, format breakdown, and newest dataset timestamp from data.egov.bg."""
    cache_file = CACHE_DIR / f"inv_v3_{org_uri}.json"
    if cache_file.exists() and (time.time() - cache_file.stat().st_mtime) < 86400:
        cached = json.loads(cache_file.read_text(encoding="utf-8"))
        if cached.get("verified"):
            return cached

    prof_html = fetch_html_cached(f"https://data.egov.bg/organisation/profile/{org_uri}", f"prof_{org_uri}.html")
    ds_count = 0
    prof_ok = bool(prof_html and 'class="data-sets"' in prof_html)
    m_cnt = re.search(r'class="data-sets"[^>]*>\s*<p>\s*(\d+)\s*</p>', prof_html, re.I | re.S)
    if m_cnt:
        ds_count = int(m_cnt.group(1))

    formats: dict[str, int] = {}
    top_datasets: list[dict[str, Any]] = []
    latest_update = ""
    ds_ok = True

    if ds_count > 0:
        ds_url = f"https://data.egov.bg/organisation/{org_uri}/datasets?sort=updated_at&order=desc"
        ds_html = fetch_html_cached(ds_url, f"ds_sorted_{org_uri}.html", timeout=28)
        ds_ok = bool(ds_html and ("dataset/" in ds_html or "намерен" in ds_html.lower()))
        # Format facets: format%5B0%5D=csv">csv (42)</a>
        for fm in re.finditer(r'format%5B0%5D=([^"&]+)"[^>]*>\s*([^<(]+?)\s*\((\d+)\)\s*</a>', ds_html, re.I):
            fmt_name = html.unescape(fm.group(2)).strip().upper()
            fmt_cnt = int(fm.group(3))
            if fmt_name and fmt_name not in formats:
                formats[fmt_name] = fmt_cnt

        # Extract top (newest!) dataset titles & URIs
        seen_ds: set[str] = set()
        for dm in re.finditer(
            r'href="https://data\.egov\.bg/organisation/dataset/([a-f0-9-]+)(?:\?[^"]*)?"[^>]*>\s*<h2[^>]*>(.*?)</h2>',
            ds_html,
            re.I | re.S,
        ):
            d_uri = dm.group(1)
            d_name = html.unescape(re.sub(r"<[^>]+>", "", dm.group(2)))
            d_name = re.sub(r"\s+", " ", d_name).strip()
            if d_uri not in seen_ds and d_name:
                seen_ds.add(d_uri)
                top_datasets.append({"uri": d_uri, "name": d_name[:140], "updated": ""})
                if len(top_datasets) >= 5:
                    break

        # Check freshest update timestamp via getDatasetDetails on top 3 newest datasets (with retry)
        for td in top_datasets[:3]:
            for det_try in range(2):
                try:
                    time.sleep(0.35 + det_try * 1.2)
                    det = post_egov_json("getDatasetDetails", {"dataset_uri": td["uri"]}, timeout=18)
                    d_obj = det.get("data") or det.get("dataset") or det
                    upd = str(d_obj.get("updated_at") or d_obj.get("created_at") or "")
                    res_map = d_obj.get("resource") or d_obj.get("resources") or {}
                    if isinstance(res_map, dict):
                        for rv in res_map.values():
                            if isinstance(rv, dict):
                                ru = str(rv.get("updated_at") or rv.get("created_at") or "")
                                if ru > upd:
                                    upd = ru
                    elif isinstance(res_map, list):
                        for rv in res_map:
                            if isinstance(rv, dict):
                                ru = str(rv.get("updated_at") or rv.get("created_at") or "")
                                if ru > upd:
                                    upd = ru
                    if upd:
                        td["updated"] = upd[:10]
                        if upd > latest_update:
                            latest_update = upd
                        break
                except Exception:
                    pass

    mr_count = sum(cnt for fmt, cnt in formats.items() if fmt in MACHINE_READABLE_FORMATS)
    fmt_total = sum(formats.values())
    if ds_count == 0 and fmt_total > 0:
        ds_count = fmt_total

    out = {
        "org_uri": org_uri,
        "verified": prof_ok and ds_ok and (ds_count == 0 or bool(latest_update)),
        "totalDatasets": ds_count,
        "formats": formats,
        "machineReadableCount": min(ds_count, mr_count),
        "latestUpdate": latest_update[:10] if latest_update else "",
        "topDatasets": top_datasets,
    }
    if out["verified"]:
        cache_file.write_text(json.dumps(out, ensure_ascii=False), encoding="utf-8")
    return out


def probe_portal_http(url: str) -> dict[str, Any]:
    cache_key = re.sub(r"[^a-zA-Z0-9]+", "_", url)[:80]
    cache_file = CACHE_DIR / f"http_{cache_key}.json"
    if cache_file.exists() and (time.time() - cache_file.stat().st_mtime) < 86400:
        return json.loads(cache_file.read_text(encoding="utf-8"))
    t0 = time.time()
    status = 0
    ctype = ""
    has_captcha = False
    has_waf = False
    err = ""
    try:
        req = urllib.request.Request(url, headers=HEADERS_GET, method="GET")
        with urllib.request.urlopen(req, context=SSL_CTX, timeout=8) as resp:
            status = getattr(resp, "status", 200)
            ctype = resp.headers.get("Content-Type", "")
            snippet = resp.read(20000).decode("utf-8", errors="ignore").lower()
            has_captcha = any(k in snippet for k in ("recaptcha", "g-recaptcha", "hcaptcha", "captcha"))
            has_waf = any(k in snippet for k in ("f5 networks", "request rejected", "support id", "cloudflare"))
    except urllib.error.HTTPError as he:
        status = he.code
        err = f"HTTP {he.code}"
        if he.code in (403, 406, 429):
            has_waf = True
    except Exception as ex:
        err = type(ex).__name__
    dt_ms = round((time.time() - t0) * 1000)
    res = {
        "httpStatus": status,
        "latencyMs": dt_ms,
        "contentType": ctype.split(";")[0].strip(),
        "hasCaptcha": has_captcha,
        "hasWaf": has_waf,
        "error": err,
    }
    cache_file.write_text(json.dumps(res, ensure_ascii=False), encoding="utf-8")
    return res


